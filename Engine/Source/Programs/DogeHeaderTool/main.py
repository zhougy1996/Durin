def main():
    process_arguments()
    logging.basicConfig(level=logging_level, format='[%(levelname)s] %(message)s')
    
    logging.info(f"Processing module: {g.module_name}")
    logging.info(f"DHT Directory: {g.dht_dir}")
    logging.info(f"Dependencies: {g.dependencies}")

    os.makedirs(g.dht_dir, exist_ok=True) # Ensure DHT directory exists

    prerequisite_ok = True

    input_headers = helper.get_input_headers()
    for header in input_headers:
        logging.info(f" - {header}")
        if not os.path.isfile(header):
            logging.error(f"Input header file does not exist: {header}")
            prerequisite_ok = False

    if not prerequisite_ok:
        sys.exit(1)

if __name__ == "__main__":
    main()