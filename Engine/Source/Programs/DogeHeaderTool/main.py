import os
import sys
import logging
import argparse

from config import *
import globals as g
import helper

def process_arguments():
    parser = argparse.ArgumentParser(description="A tool to process header files and generate code for Doge Engine.")
    parser.add_argument("--module", help="Specify the module to process.", required=True)
    parser.add_argument("--deps", help="Specify the module dependencies, should be <dir>/<module_name>.json files separated by semicolons. These files can be generated by DogeHeaderTool.", default="")
    args = parser.parse_args()

    g.module_name = args.module
    g.dht_dir = helper.get_dht_dir(g.module_name)
    if args.deps:
        g.dependencies = [dep.strip() for dep in args.deps.split(";") if dep.strip()]


def check_need_collect_module_info() -> bool:
    module_info_file = helper.get_dht_module_filepath(g.module_name)
    if not os.path.isfile(module_info_file):
        return True
    timestamp = os.path.getmtime(module_info_file)
    input_headers = helper.get_input_headers()
    # If any input header is newer than the module info file, we need to collect info
    for header in input_headers:
        if os.path.getmtime(header) > timestamp:
            return True
    return False

